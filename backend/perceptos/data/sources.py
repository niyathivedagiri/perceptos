class DataSourceStatus(str, Enum):
    """Where a value's underlying bytes came from. Never inferred loosely."""

    #: Fetched live from a NASA/USGS endpoint that requires no credentials.
    NASA_PUBLIC_NO_KEY = "NASA_PUBLIC_NO_KEY"
    #: Fetched live using the shared DEMO_KEY. Heavily rate-limited.
    NASA_DEMO_KEY = "NASA_DEMO_KEY"
    #: Fetched live using the operator's own api.nasa.gov key.
    NASA_PERSONAL_KEY = "NASA_PERSONAL_KEY"
    #: Real NASA data, previously downloaded, now read from disk. Still real —
    #: but not live, and the distinction matters for a "current conditions"
    #: claim.
    LOCAL_CACHED_DATA = "LOCAL_CACHED_DATA"
    #: Synthetic. Generated by PerceptOS. Never mixed with the above.
    SIMULATION = "SIMULATION"
    #: The dataset is genuinely not present. This is not simulation, and must
    #: not be silently replaced by it.
    UNAVAILABLE = "UNAVAILABLE"

    @property
    def is_live(self) -> bool:
        return self in (self.NASA_PUBLIC_NO_KEY, self.NASA_DEMO_KEY,
                        self.NASA_PERSONAL_KEY)

    @property
    def is_real(self) -> bool:
        """Real measurement, whether fetched now or read from cache."""
        return self.is_live or self is DataSourceStatus.LOCAL_CACHED_DATA

    @property
    def badge(self) -> str:
        """Short label for the UI."""
        return {
            DataSourceStatus.NASA_PUBLIC_NO_KEY: "LIVE · NASA",
            DataSourceStatus.NASA_DEMO_KEY: "LIVE · NASA (demo key)",
            DataSourceStatus.NASA_PERSONAL_KEY: "LIVE · NASA",
            DataSourceStatus.LOCAL_CACHED_DATA: "CACHED REAL DATA",
            DataSourceStatus.SIMULATION: "SIMULATION",
            DataSourceStatus.UNAVAILABLE: "UNAVAILABLE",
        }[self]

    @property
    def severity(self) -> str:
        """Drives the UI colour. Synthetic and missing data must stand out."""
        if self.is_live:
            return "ok"
        if self is DataSourceStatus.LOCAL_CACHED_DATA:
            return "info"
        if self is DataSourceStatus.SIMULATION:
            return "warn"
        return "error"


class StereoStatus(str, Enum):
    """How much a stereo pair can actually be trusted.

    A pair of images from two cameras is not a stereo pair. Depth requires
    that the two frames were acquired together, that the geometry between the
    cameras is known, and that the epipolar lines have been made horizontal.
    Each of those is a separate claim, so each gets its own state.
    """

    #: Rectified, calibrated, ready for block matching. Depth is valid.
    RECTIFIED_STEREO = "RECTIFIED_STEREO"
    #: Same acquisition and a real camera model is present, but the pair has
    #: not been rectified. Feature matching is valid; scanline matching is not.
    VALID_STEREO = "VALID_STEREO"
    #: Not a stereo pair: the frames failed a precondition (different
    #: instruments, different sols, or not a simultaneous exposure). The images
    #: are individually valid; treating them as a pair is not.
    UNRECTIFIED_PAIR = "UNRECTIFIED_PAIR"
    #: The archive supplied no camera model. Baseline and focal length are
    #: therefore unknown, and PerceptOS will not invent them.
    CALIBRATION_UNAVAILABLE = "CALIBRATION_UNAVAILABLE"
    #: Synthetic pair with a known synthetic geometry.
    SIMULATION = "SIMULATION"

    @property
    def depth_valid(self) -> bool:
        """Only one state permits a metric depth map."""
        return self in (StereoStatus.RECTIFIED_STEREO, StereoStatus.SIMULATION)

    @property
    def severity(self) -> str:
        return {
            StereoStatus.RECTIFIED_STEREO: "ok",
            StereoStatus.VALID_STEREO: "info",
            StereoStatus.UNRECTIFIED_PAIR: "warn",
            StereoStatus.CALIBRATION_UNAVAILABLE: "error",
            StereoStatus.SIMULATION: "warn",
        }[self]


class LabelProvenance(str, Enum):
    """Where a terrain label came from.

    Displaying an AI4Mars ground-truth mask and calling it segmentation output
    would be a straightforward misrepresentation: the dataset labels were drawn
    by humans, not predicted. These states keep the two apart.
    """

    #: Human-annotated dataset label (AI4Mars). Not a model output.
    GROUND_TRUTH_LABEL = "GROUND_TRUTH_LABEL"
    #: Produced by a trained model at inference time.
    MODEL_PREDICTION = "MODEL_PREDICTION"
    #: Synthetic labels generated for demonstration.
    SIMULATION = "SIMULATION"
    #: No labels for this frame.
    UNAVAILABLE = "UNAVAILABLE"

    @property
    def severity(self) -> str:
        return {
            LabelProvenance.GROUND_TRUTH_LABEL: "ok",
            LabelProvenance.MODEL_PREDICTION: "info",
            LabelProvenance.SIMULATION: "warn",
            LabelProvenance.UNAVAILABLE: "error",
        }[self]


@dataclass(frozen=True, slots=True)
class NasaService:
    """One external data service, described precisely enough to audit."""

    key: str
    name: str
    endpoint: str
    provides: str
    requires_api_key: bool
    demo_key_sufficient: Optional[bool]
    personal_key_recommended: bool
    env_var: Optional[str]
    rate_limit: str
    used_by: str
    on_missing_key: str
    credit: str
    licence: str
    verified_utc: str = "2026-08-12"
    notes: str = ""

    def to_dict(self) -> dict[str, Any]:
        return {
            "key": self.key,
            "name": self.name,
            "endpoint": self.endpoint,
            "provides": self.provides,
            "requires_api_key": self.requires_api_key,
            "demo_key_sufficient": self.demo_key_sufficient,
            "personal_key_recommended": self.personal_key_recommended,
            "env_var": self.env_var,
            "rate_limit": self.rate_limit,
            "used_by": self.used_by,
            "on_missing_key": self.on_missing_key,
            "credit": self.credit,
            "licence": self.licence,
            "verified_utc": self.verified_utc,
            "notes": self.notes,
        }


