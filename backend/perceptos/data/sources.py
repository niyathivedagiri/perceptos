"""
perceptos.data.sources
======================

The register of where data can come from, and what that means for trust.

This module exists because "real NASA data" is not one thing. PerceptOS talks
to two entirely different NASA services with different access models, different
metadata richness and different key requirements, and it must never let a
cached file, a simulated grid or a demo-key response be presented as the same
thing as a live archive fetch.

:class:`DataSourceStatus` is the vocabulary. Every dataset, every frame source
and every API response reports one, and the UI badges them distinctly.

Verified against NASA documentation on 2026-08-12
--------------------------------------------------

**1. JPL Mars 2020 Raw Image API** — ``NASA_PUBLIC_NO_KEY``

  ``https://mars.nasa.gov/rss/api/?feed=raw_images&category=mars2020&feedtype=json``

  The machine interface behind the official Perseverance raw-image archive at
  ``mars.nasa.gov/mars2020/multimedia/raw-images/``. Requires **no API key**
  and is not rate-limited by api.data.gov. Returns substantially richer
  metadata than the Mars Rover Photos API below — including the spacecraft
  clock, rover attitude quaternion, site/drive indices and, critically, the
  **camera model** (CAHV/CAHVOR component list). That camera model is what
  makes honest stereo possible: without it, baseline and focal length would
  have to be invented, which this project will not do.

  This is the preferred source and the one PerceptOS uses by default.

**2. NASA Mars Rover Photos API** — ``NASA_DEMO_KEY`` / ``NASA_PERSONAL_KEY``

  ``https://api.nasa.gov/mars-photos/api/v1/rovers/perseverance/photos``

  A community-built index served through api.nasa.gov. Requires a key.
  ``DEMO_KEY`` is limited to 30 requests/hour and 50/day per IP; a free
  personal key raises that to 1,000 requests/hour. Its JSON carries only
  ``id``, ``sol``, ``earth_date``, a camera name and an image URL — no
  spacecraft clock, no attitude, **no camera model**. PerceptOS keeps it as a
  fallback and cross-check, not as the primary source.

**3. USGS Astrogeology / HiRISE DTM** — ``NASA_PUBLIC_NO_KEY``

  Jezero crater digital terrain models at 1 m/pixel. Direct HTTP download, no
  key. Large files, so PerceptOS prints instructions rather than pulling them
  unattended.

**4. AI4Mars (Zenodo)** — ``NASA_PUBLIC_NO_KEY``

  Semantic terrain labels produced by JPL. Zenodo download, no key.

None of these require authentication except service 2, and service 2 is the
one PerceptOS does *not* need.
"""

