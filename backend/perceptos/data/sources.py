def resolve_key_status(api_key: Optional[str] = None) -> DataSourceStatus:
    """Classify the api.nasa.gov credential currently in effect.

    Reports what is actually configured, not what someone intended. An empty
    or whitespace key resolves to DEMO_KEY because that is what will be sent.
    """
    key = (api_key or os.environ.get("NASA_API_KEY") or "").strip()
    if not key or key.upper() == "DEMO_KEY":
        return DataSourceStatus.NASA_DEMO_KEY
    return DataSourceStatus.NASA_PERSONAL_KEY


def credentials_report(api_key: Optional[str] = None) -> dict[str, Any]:
    """Everything an operator needs to know about credentials, in one payload.

    Surfaced at ``GET /api/datasources`` so the answer to "do I need a NASA
    key?" is available from the running system rather than only from a README
    that may have drifted.
    """
    status = resolve_key_status(api_key)
    keyless = [s for s in NASA_SERVICES.values() if not s.requires_api_key]
    keyed = [s for s in NASA_SERVICES.values() if s.requires_api_key]
    return {
        "verified_utc": "2026-08-12",
        "api_nasa_gov_key_status": status.value,
        "api_nasa_gov_key_configured": status is DataSourceStatus.NASA_PERSONAL_KEY,
        "env_var": "NASA_API_KEY",
        "primary_perseverance_source": "jpl_raw_images",
        "primary_source_requires_key": False,
        "summary": (
            "PerceptOS's primary Perseverance source (the JPL Mars 2020 Raw "
            "Image API) requires NO credentials. A NASA API key is only needed "
            "for the optional Mars Rover Photos fallback."
        ),
        "services_without_key": [s.key for s in keyless],
        "services_requiring_key": [s.key for s in keyed],
        "services": {k: s.to_dict() for k, s in NASA_SERVICES.items()},
        "status_vocabulary": {
            s.value: {"badge": s.badge, "severity": s.severity,
                      "is_live": s.is_live, "is_real": s.is_real}
            for s in DataSourceStatus
        },
        "stereo_vocabulary": {
            s.value: {"depth_valid": s.depth_valid, "severity": s.severity}
            for s in StereoStatus
        },
        "label_vocabulary": {s.value: {"severity": s.severity}
                             for s in LabelProvenance},
    }
